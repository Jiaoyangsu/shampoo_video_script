#!/usr/bin/env python3
"""Build training JSON, quality report and a human review sheet from rewrite JSONL."""
from __future__ import annotations

import argparse
import csv
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Sequence

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.data.rewrite import convert_for_training  # noqa: E402
from src.script_schema import validate_script  # noqa: E402


def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dir", default="data/rewrite_30s")
    parser.add_argument("--split", default="train")
    args = parser.parse_args(argv)

    root = Path(args.dir)
    accepted = read_jsonl(root / ("%s_accepted.jsonl" % args.split))
    rejected = read_jsonl(root / ("%s_rejected.jsonl" % args.split))
    train = convert_for_training(accepted)
    (root / ("%s.json" % args.split)).write_text(
        json.dumps(train, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    reasons: Dict[str, int] = {}
    for row in rejected:
        attempts = row.get("attempts") or []
        errors = attempts[-1].get("errors", []) if attempts else ["unknown"]
        for error in errors[:3]:
            key = error.split(":")[0][:80]
            reasons[key] = reasons.get(key, 0) + 1

    report = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "split": args.split,
        "accepted": len(accepted),
        "rejected": len(rejected),
        "accept_rate": round(len(accepted) / max(1, len(accepted) + len(rejected)), 4),
        "failure_reasons": reasons,
        "config": {
            "target_duration_sec": 30,
            "min_shots": 10,
            "max_shots": 12,
        },
    }
    (root / ("%s_quality.json" % args.split)).write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    review_path = root / ("%s_review.csv" % args.split)
    with review_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(
            [
                "id",
                "source_index",
                "n_shots",
                "duration_sec",
                "shot_types",
                "flags",
                "voiceovers",
                "visual_descriptions",
                "input",
            ]
        )
        for row in accepted:
            shots = row.get("output", [])
            metrics = validate_script(
                shots, min_shots=1, require_music=True, enforce_pacing=False
            ).metrics
            flags = []
            voiceovers = [s.get("voiceover", "") for s in shots]
            if "限时优惠" in " ".join(voiceovers):
                flags.append("generic_cta")
            if len(set(voiceovers)) < len(voiceovers):
                flags.append("duplicate_voiceover")
            if len({s.get("shot_type", "") for s in shots}) < 4:
                flags.append("low_type_diversity")
            if any(len(s.get("visual_description", "")) < 10 for s in shots):
                flags.append("short_visual")
            writer.writerow(
                [
                    row.get("id", ""),
                    row.get("source_index", ""),
                    len(shots),
                    metrics.get("total_duration_sec", ""),
                    " | ".join(s.get("shot_type", "") for s in shots),
                    ",".join(flags),
                    " | ".join(voiceovers),
                    " | ".join(s.get("visual_description", "") for s in shots),
                    row.get("input", ""),
                ]
            )

    readme = root / ("%s_README.md" % args.split)
    readme.write_text(
        """# Rewrite 30s dataset

Generated by `scripts/rewrite_data.py` with a local Ollama model.

- `{split}.json` — accepted rows for SFT, with `target_duration_sec` / `target_shots`
- `{split}_accepted.jsonl` / `{split}_rejected.jsonl` — audit trail
- `{split}_quality.json` — accept/reject counts and failure reasons
- `{split}_review.csv` — human spot-check sheet

**Status: draft, needs human review.** The model is asked to write 10-12 shots,
28-32 seconds, <=4 chars/sec, and a validator rejects missing fields, bad time
axes, invented brands and over-long voiceovers. Timing is normalized
deterministically after generation; content quality still needs a human.

Review workflow:
1. Open `{split}_review.csv`.
2. Reject rows with generic copy, repeated CTA, wrong claims, or unusable visuals.
3. For rejected rows, rerun the rewrite with a tighter brief or fix by hand.
""".format(split=args.split),
        encoding="utf-8",
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print("Wrote", root / ("%s.json" % args.split), "and", review_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
